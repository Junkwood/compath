SELECT
	P.PARENT_PROJECT_ID,
	P2.PROJECT_NAME AS PARENT_PROJECT_NAME,
	AVG(NVL(T.PROGRESS_RATE,0)) AS PROGRESS_RATE
FROM PROJECTS P
LEFT JOIN PROJECTS P2
	ON P.PARENT_PROJECT_ID = P2.PROJECT_ID 
LEFT JOIN TASKS T
	ON P.PROJECT_ID = T.PROJECT_ID
WHERE P.PARENT_PROJECT_ID IS NOT NULL
GROUP BY
	P.PARENT_PROJECT_ID ,
	P2.PROJECT_NAME
ORDER BY
	P.PARENT_PROJECT_ID;

