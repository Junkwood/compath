SELECT
	P.PROJECT_ID,
	P.PARENT_PROJECT_ID,
    (SELECT PROJECT_NAME FROM PROJECTS P2 WHERE P2.PARENT_PROJECT_ID=P.PROJECT_ID) AS PARENT_PROJECT_NAME,
	P.PROJECT_NAME,
    P.END_DATE,
    P.PM_USER_ID,
	AVG(NVL(T.PROGRESS_RATE,0)) AS PROGRESS_RATE
FROM PROJECTS P JOIN TASKS T
ON P.PROJECT_ID = T.PROJECT_ID
GROUP BY 
	P.PARENT_PROJECT_ID,
	P.PROJECT_ID, 
	P.PROJECT_NAME, 
	P.END_DATE, 
	P.PM_USER_ID 
ORDER BY P.PARENT_PROJECT_ID;

